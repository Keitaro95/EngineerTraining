"""文面判定に使う語彙・絵文字の重み辞書。

ここが判定の「主観」が入る唯一の場所。納得できない結果が出たら、
モデルではなくこの表を直せば挙動が変わる（それがルールベースの利点）。

weight は 1 メッセージあたりの寄与。目安:
   +3 = 恋愛的好意としてかなり強い / -3 = 明確な後退
ambiguous=True の項目は誤検出しやすい（例:「好き」は物に対しても使う）ため
重みを低めにし、レポート上で注記する。
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Rule:
    name: str
    pattern: re.Pattern
    weight: float
    ambiguous: bool = False


def _r(name: str, pattern: str, weight: float, ambiguous: bool = False) -> Rule:
    return Rule(name, re.compile(pattern), weight, ambiguous)


