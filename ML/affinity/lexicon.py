# 絵文字・記号の温度
# --------------------------------------------------------------------------
EMOJI_WEIGHTS: dict[str, float] = {
    # 恋愛的な温度が高い
    "❤️": 2.5, "❤": 2.5, "🩷": 2.5, "💕": 2.2, "💖": 2.2, "💗": 2.0, "💓": 2.0,
    "😍": 2.2, "🥰": 2.2, "😘": 2.5, "💘": 2.5, "💞": 2.0, "💌": 2.0,
    # 好意的だが友人でも使う
    "😊": 0.8, "☺️": 0.8, "😄": 0.6, "🥺": 1.0, "😌": 0.5, "🤗": 0.8, "✨": 0.4,
    "🎵": 0.3, "🌸": 0.4, "😳": 1.0,
    # 中立・社交辞令として頻出（温度の証拠にならない）
    "😂": 0.0, "🤣": 0.0, "😅": -0.2, "👍": -0.2, "🙏": -0.2, "🙇": -0.3,
    "😇": 0.0, "💦": -0.3, "😓": -0.4, "🥲": -0.2, "👌": -0.2,
}

# 疑問形の検出（相手がこちらに関心を向けているかの指標）
QUESTION_PATTERN = re.compile(
    r"[?？]|(何|なに|どこ|いつ|誰|だれ|どう|どんな|なんで|どうして|どっち)(です)?か?[?？]?\s*$"
)

# 自分（me）が誘いを出しているメッセージの検出
INVITATION_PATTERN = re.compile(
    r"(行きませんか|行かない\?|行こう|会えます|会える|会いませんか|"
    r"どうですか|空いてる|空いていますか|予定(は)?どう|ご飯|飲み|映画|ランチ|ディナー)"
)

# 誘いに対する相手の応答分類
INVITATION_ACCEPT = re.compile(
    r"(行きたい|行こう|行けます|いいね|いいですね|ぜひ|楽しみ|大丈夫(です)?|空いてる|うん[、。!！]?$|オッケー|OK)"
)
INVITATION_DECLINE = re.compile(
    r"(ごめん|すみません|忙し|無理|厳しい|難しい|また今度|行けな|会えな|予定(が)?ある)"
)


def emoji_score(text: str) -> tuple[float, list[str]]:
    """本文中の絵文字による加点と、検出した絵文字の一覧を返す。"""
    total = 0.0
    found: list[str] = []
    for emoji, weight in EMOJI_WEIGHTS.items():
        count = text.count(emoji)
        if count:
            # 同じ絵文字の連打は 2 個までしか数えない（❤❤❤❤ で青天井にしない）
            total += weight * min(count, 2)
            found.append(emoji)
    return total, found
